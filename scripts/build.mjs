import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { parse } from "acorn";
import {
  buildConversationFork,
  buildAttachmentFork,
} from "./conversation-fork.mjs";
import { buildSidebarFork } from "./sidebar-fork.mjs";

const root = new URL("../", import.meta.url);
const artifact = (packageName) =>
  new URL(
    `runtime-evidence/dsh/node_modules/@deepseek-ai/${packageName}/lib/client.js`,
    root,
  );

function moduleFactory(source, id) {
  const ast = parse(source, { ecmaVersion: "latest", sourceType: "module" });
  const replacements = [];
  const names = [];
  for (const node of ast.body) {
    if (node.type === "ImportDeclaration") {
      const path = node.source.value.startsWith("./")
        ? `dsh-multi-panel/${node.source.value.slice(2).replace(/\.mjs$/, "")}`
        : node.source.value;
      const statements = node.specifiers.map((specifier) => {
        if (specifier.type === "ImportDefaultSpecifier")
          return `const ${specifier.local.name} = require(${JSON.stringify(path)}).default ?? require(${JSON.stringify(path)});`;
        if (specifier.type === "ImportNamespaceSpecifier")
          return `const ${specifier.local.name} = require(${JSON.stringify(path)});`;
        return `const ${specifier.local.name} = require(${JSON.stringify(path)})[${JSON.stringify(specifier.imported.name)}];`;
      });
      replacements.push({
        start: node.start,
        end: node.end,
        text: statements.join("\n"),
      });
    } else if (node.type === "ExportNamedDeclaration" && node.declaration) {
      replacements.push({
        start: node.start,
        end: node.declaration.start,
        text: "",
      });
      if (node.declaration.id) names.push(node.declaration.id.name);
      else
        for (const declaration of node.declaration.declarations)
          names.push(declaration.id.name);
    } else if (node.type.startsWith("Export")) {
      throw new Error(`Unsupported export in owned module ${id}`);
    }
  }
  let output = source;
  for (const replacement of replacements.sort((a, b) => b.start - a.start))
    output =
      output.slice(0, replacement.start) +
      replacement.text +
      output.slice(replacement.end);
  return `${JSON.stringify(id)}: function(require, exports) {\n${output}\nObject.assign(exports, { ${names.join(", ")} });\n}`;
}

function captureNativeModule(source, name) {
  const prefix = "window.__ModuleLoader__.load({";
  const end = source.lastIndexOf("\n});");
  if (!source.startsWith(prefix) || end < 0)
    throw new Error("Native module wrapper changed");
  return `const ${name} = {${source.slice(prefix.length, end)}\n};`;
}

const conversation = buildConversationFork(
  await readFile(artifact("dsh-client-ui-conversation"), "utf8"),
);
const sidebar = buildSidebarFork(
  await readFile(artifact("dsh-client-ui-sidebar-right"), "utf8"),
);
const attachment = buildAttachmentFork(
  await readFile(artifact("dsh-client-ui-attachment"), "utf8"),
);
const factories = [];
for (const name of [
  "preferences",
  "undo-notice",
  "settings",
  "shortcuts",
  "split-model",
  "workspace-state",
  "workspace",
]) {
  factories.push(
    moduleFactory(
      await readFile(new URL(`client/${name}.mjs`, root), "utf8"),
      `dsh-multi-panel/${name}`,
    ),
  );
}
const css = await readFile(new URL("client/workspace.css", root), "utf8");
const client = `// DSH 0.2.0-rc.2 pinned native owners; generated by scripts/build.mjs.\n// Bundled upstream code: see THIRD_PARTY_NOTICES.md and third-party-licenses/.\nwindow.__ModuleLoader__.load({
  id: 'dsh-multi-panel',
  factory(requireNative) {
    const factories = { ${factories.join(",\n")} };
    const cache = Object.create(null);
    function require(id) {
      if (!Object.hasOwn(factories, id)) return requireNative(id);
      if (!cache[id]) { cache[id] = {}; factories[id](require, cache[id]); }
      return cache[id];
    }
    ${captureNativeModule(conversation, "conversationModule")}
    ${captureNativeModule(sidebar, "sidebarModule")}
    ${captureNativeModule(attachment, "attachmentModule")}
    const conversation = conversationModule.factory(require);
    const sidebar = sidebarModule.factory(require);
    const attachment = attachmentModule.factory(require);
    return {
      inject: [...new Set([...conversation.inject, ...sidebar.inject, ...attachment.inject])],
      Config: conversation.Config,
      apply(ctx, config) {
        ctx.effect(() => {
          const style = document.createElement('style');
          style.dataset.multiPanelWorkspace = '';
          style.textContent = ${JSON.stringify(css)};
          document.head.appendChild(style);
          return () => style.remove();
        }, 'multi-panel: workspace styles');
        const preferencesSource = require('dsh-multi-panel/preferences').createPreferencesSource(ctx.configForms.get('multi-panel'));
        require('dsh-multi-panel/settings').registerMultiPanelSettings(ctx, preferencesSource);
        conversation.apply(ctx, { ...config, multiPanelPreferences: preferencesSource });
        sidebar.apply(ctx, { preferencesSource });
        attachment.apply(ctx);
        ctx.layout.closeRightbar();
      },
    };
  },
});\n`;
parse(client, { ecmaVersion: "latest", sourceType: "script" });
await mkdir(new URL("lib/", root), { recursive: true });
await writeFile(new URL("lib/client.js", root), client);
await writeFile(
  new URL("lib/preferences.js", root),
  await readFile(new URL("client/preferences.mjs", root), "utf8"),
);
await writeFile(
  new URL("lib/index.js", root),
  `// Preserve the pinned native Host's busy-Enter and optional auto:false registration.\n// Profile native-peer links can point at another CLI version, so do not import its Host Config.\nimport Schema from '@deepseek-ai/schemastery';\nimport { preferenceSchemaFields } from './preferences.js';\nexport const Config = Schema.object({ busyEnter: Schema.union(['queue', 'steer']).default('queue').volatile(), ...preferenceSchemaFields(Schema) });\nexport function apply(ctx) {\n  ctx.inject(['settings'], child => {\n    child.effect(() => child.settings.configure({ auto: false }, ctx.fiber));\n  });\n}\n`,
);
console.log(
  `Built ${fileURLToPath(new URL("lib/client.js", root))} (${Buffer.byteLength(client)} bytes). Native conversation/sidebar/shell SHA-256 verified.`,
);
